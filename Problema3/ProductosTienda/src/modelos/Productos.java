package modelos;

public class Productos {

    private String codigo;
    private String nombre;
    private float precio;
    private int cantidad;

    public Producto() {
    }

    public Producto(String codigo, String nombre, float precio, int cantidad) {
        this.codigo = codigo;
        this.nombre = nombre;
        this.precio = precio;
        this.cantidad = cantidad;
    }


}
